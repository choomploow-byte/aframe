/**
 * Code export (docs/10): the exporter registry. `exportDesign` turns one node of a document into a
 * set of files for a format; writing them to disk is somebody else's job (and is confined, see
 * `mcp/export-write.ts` and the desktop app's `export_files`). Pure and deterministic: the same
 * design always gives the same bytes, so a re-export changes only what the design changed.
 */
import { CoreError } from '../errors';
import { lookupId } from '../ops';
import { RESET_CSS } from './format';
import { toHtml } from './html';
import { buildIr, fontsourcePackage, type ExportFile, type IrResult } from './ir';
import { kebab, pascal } from './names';
import { toReactCss } from './jsx';
import { toReactTailwind } from './tailwind';
import type { Doc } from '../types';

export type ExportFormat = 'html' | 'react-css' | 'react-tailwind';

export const EXPORT_FORMATS: readonly { id: ExportFormat; label: string; description: string }[] = [
  { id: 'html', label: 'HTML + CSS', description: 'index.html and styles.css, no framework.' },
  {
    id: 'react-css',
    label: 'React + CSS Modules',
    description: 'A TSX component with its own CSS Module and a tokens stylesheet.',
  },
  {
    id: 'react-tailwind',
    label: 'React + Tailwind',
    description:
      'A TSX component using Tailwind v4 utilities, a @theme from your tokens, and a small CSS file for what has no exact utility.',
  },
];

export interface ExportResult {
  format: ExportFormat;
  /** The file to look at first (what a preview shows). */
  main: string;
  files: ExportFile[];
  warnings: string[];
  componentName: string;
}

export interface ExportOptions {
  /** Component name for the React formats (default: from the frame's name). */
  componentName?: string;
}

const MAX_FILES = 200;

export function exportDesign(
  doc: Doc,
  nodeRef: string,
  format: ExportFormat,
  options: ExportOptions = {},
): ExportResult {
  const nodeId = lookupId(doc.nodes, nodeRef);
  const node = doc.nodes[nodeId];
  if (!node) {
    throw new CoreError(
      'NOT_FOUND',
      `Node ${nodeRef} does not exist.`,
      'Call get_design to see the ids.',
    );
  }
  if (node.type === 'page') {
    throw new CoreError(
      'INVALID_VALUE',
      'Export a frame (or any node on the page), not the page itself.',
      'Pass the id of a top-level frame.',
    );
  }
  if (!node.visible) {
    throw new CoreError('INVALID_VALUE', `${nodeId} is hidden, so there is nothing to export.`);
  }

  const componentName = options.componentName
    ? pascal(options.componentName)
    : pascal(node.name, 'Design');
  const ir: IrResult = buildIr(doc, nodeId, { tokens: 'variables' });
  let files: ExportFile[];
  let main: string;
  switch (format) {
    case 'html':
      files = toHtml(ir, node.name);
      main = 'index.html';
      break;
    case 'react-css':
      files = toReactCss(ir, componentName);
      main = `${componentName}.tsx`;
      break;
    case 'react-tailwind': {
      files = toReactTailwind(ir, componentName);
      // Tailwind's own reset is used here, but a plain body font keeps text without a family the same.
      const extra = files.find((f) => f.path === 'atelier.css');
      if (extra && typeof extra.content === 'string') {
        extra.content = `body {\n  font-family: var(--font-body, 'Inter', system-ui, sans-serif);\n}\n\n${extra.content}`;
      }
      main = `${componentName}.tsx`;
      break;
    }
  }
  if (files.length + 1 > MAX_FILES) {
    throw new CoreError(
      'LIMIT_EXCEEDED',
      `That would write ${files.length} files; the limit is ${MAX_FILES}.`,
    );
  }
  files.push({
    path: 'README-atelier.md',
    content: readme(format, componentName, node.name, files, ir),
  });
  return { format, main, files, warnings: ir.warnings, componentName };
}

function readme(
  format: ExportFormat,
  componentName: string,
  frameName: string,
  files: readonly ExportFile[],
  ir: IrResult,
): string {
  const fonts = ir.fonts
    .map((f) => ({ family: f, pkg: fontsourcePackage(f) }))
    .map((f) =>
      f.pkg ? `- ${f.family}: \`npm i ${f.pkg}\`` : `- ${f.family}: install or load it yourself`,
    );
  const list = files.map((f) => `- \`${f.path}\``);
  const howTo =
    format === 'html'
      ? 'Open `index.html` in a browser, or copy the markup and `styles.css` into your page.'
      : format === 'react-css'
        ? `Copy this folder into your project and render \`<${componentName} />\`. It needs a bundler that handles \`*.module.css\` and image imports (Vite does).`
        : `Copy this folder into a project that has Tailwind v4 (\`npm i tailwindcss @tailwindcss/vite\` and the Vite plugin) and render \`<${componentName} />\`.`;
  return `# ${frameName}

Generated by Atelier. ${howTo}

## Files
${list.join('\n')}

## Fonts
${fonts.length > 0 ? fonts.join('\n') : '- The design sets no fonts of its own.'}

Import the font in your app (for example \`import '@fontsource-variable/inter';\`) so text renders in the same face as the design.

## Hand-editing
- Class names come from the layer names and are stable: exporting again after a design change keeps them, so a diff shows only what changed. Rename a layer in Atelier to rename its class.
- Colours, fonts and corner radii that came from tokens are CSS variables (\`--color-*\`, \`--font-*\`, \`--radius-*\`); change them in one place.
- Elements placed by x and y are marked with a comment: consider converting them to auto-layout in your own code.
- Exporting again with the same folder does not overwrite files you have edited unless you ask it to.
${ir.warnings.length > 0 ? `\n## Notes from the export\n${ir.warnings.map((w) => `- ${w}`).join('\n')}\n` : ''}`;
}

export { buildIr, kebab, pascal, RESET_CSS };
export type { ExportFile };

// Generates src/canvas/fonts.css: @font-face aliases that register the bundled variable fonts under
// their plain names ("Inter", not fontsource's "Inter Variable"). A document says
// fontFamily: "Inter", nodeToCss emits "Inter", and exported code uses the same name, so the canvas
// has to answer to it. Latin + Latin Extended only (docs/19). Run: node scripts/gen-fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const FONTS = [
  ['inter', 'Inter'],
  ['fraunces', 'Fraunces'],
  ['dm-sans', 'DM Sans'],
  ['space-grotesk', 'Space Grotesk'],
  ['playfair-display', 'Playfair Display'],
  ['jetbrains-mono', 'JetBrains Mono'],
  ['fredoka', 'Fredoka'],
];

// Single-weight display families for game UI (@fontsource/<pkg>, weight 400 only).
const STATIC_FONTS = [
  ['lilita-one', 'Lilita One'],
  ['luckiest-guy', 'Luckiest Guy'],
  ['bungee', 'Bungee'],
];

const out = [
  '/* GENERATED by scripts/gen-fonts-css.mjs from @fontsource-variable/* and @fontsource/*. Do not edit by hand. */',
  '',
];

for (const [pkg, family] of FONTS) {
  const css = readFileSync(`node_modules/@fontsource-variable/${pkg}/wght.css`, 'utf8');
  const blocks = css.split(/\n(?=\/\* )/).filter((b) => b.includes('@font-face'));
  let kept = 0;
  for (const block of blocks) {
    const comment = /^\/\* (.+?) \*\//.exec(block)?.[1] ?? '';
    if (!comment.endsWith('-latin-wght-normal') && !comment.endsWith('-latin-ext-wght-normal'))
      continue;
    const rewritten = block
      .replace(/font-family: '[^']+'/, `font-family: '${family}'`)
      .replace(
        /url\(\.\/files\/([^)]+)\)/,
        `url(../../node_modules/@fontsource-variable/${pkg}/files/$1)`,
      );
    out.push(rewritten.trim(), '');
    kept += 1;
  }
  if (kept !== 2) throw new Error(`${pkg}: expected latin and latin-ext, found ${kept}`);
}

for (const [pkg, family] of STATIC_FONTS) {
  for (const subset of ['latin', 'latin-ext']) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${subset}-400.css`, 'utf8');
    const block = css.split(/\n(?=\/\* )/).find((b) => b.includes('@font-face'));
    if (!block) throw new Error(`${pkg}: no @font-face in ${subset}-400.css`);
    const rewritten = block
      .replace(/font-family: '[^']+'/, `font-family: '${family}'`)
      // woff2 only: every webview Atelier runs in supports it, and the woff copy would double the size.
      .replace(
        /url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\),\s*url\([^)]+\) format\('woff'\)/,
        `url(../../node_modules/@fontsource/${pkg}/files/$1) format('woff2')`,
      );
    if (!rewritten.includes('../../node_modules'))
      throw new Error(`${pkg}: could not rewrite the font url`);
    out.push(rewritten.trim(), '');
  }
}

writeFileSync('src/canvas/fonts.css', `${out.join('\n')}\n`);
console.log(`wrote src/canvas/fonts.css (${FONTS.length + STATIC_FONTS.length} families)`);

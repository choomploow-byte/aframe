// Embeds the markdown the MCP server ships (skills, the Claude skill, server instructions, prompt
// recipes) into mcp/generated.ts, so the bundle is one file and nothing is read from disk at run
// time. Run by `npm run build:mcp`; the output is committed and a test fails if it drifts from the
// sources (docs/20: "Add a skill" -> regenerate).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n');

const NOT_LOADABLE = new Set(['README.md', 'atelier-SKILL.md']);
const frontmatter = (text) => {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const get = (key) => new RegExp(`^${key}:\\s*(.+)$`, 'm').exec(m?.[1] ?? '')?.[1]?.trim();
  return {
    name: get('name'),
    description: get('description'),
    body: m ? text.slice(m[0].length) : text,
  };
};

const skills = readdirSync(join(root, 'skills'))
  .filter((f) => f.endsWith('.md') && !NOT_LOADABLE.has(f))
  .sort()
  .map((f) => {
    const text = read(`skills/${f}`);
    const fm = frontmatter(text);
    const name = fm.name ?? f.replace(/\.md$/, '');
    if (!fm.description) throw new Error(`skills/${f} needs a description in its frontmatter`);
    return { name, description: fm.description, body: text };
  });

const instructionsDoc = read('prompts/mcp-server-instructions.md');
const instructions = /```\n([\s\S]*?)\n```/.exec(instructionsDoc)?.[1];
if (!instructions)
  throw new Error('prompts/mcp-server-instructions.md: no fenced instructions block');

// "## 1. Improve my design" + a fenced prompt.
const recipesDoc = read('prompts/design-agent-prompts.md');
const recipes = [
  ...recipesDoc.matchAll(/^## \d+\. (.+)\n(?:\*\*Say:\*\*.*\n)?```\n([\s\S]*?)\n```/gm),
].map((m) => ({
  title: m[1],
  text: m[2],
}));

const pkg = JSON.parse(read('package.json'));

const out = `// GENERATED by scripts/gen-mcp-data.mjs from skills/*.md and prompts/*.md. Do not edit.
export const MCP_VERSION = ${JSON.stringify(pkg.version)};

export const SERVER_INSTRUCTIONS = ${JSON.stringify(instructions)};

export interface EmbeddedSkill {
  name: string;
  description: string;
  /** The whole file, frontmatter included. */
  body: string;
}
export const SKILLS: readonly EmbeddedSkill[] = ${JSON.stringify(skills, null, 2)};

/** skills/atelier-SKILL.md: installed as ~/.claude/skills/atelier/SKILL.md. */
export const ATELIER_SKILL = ${JSON.stringify(read('skills/atelier-SKILL.md'))};

export const PROMPT_RECIPES: readonly { title: string; text: string }[] = ${JSON.stringify(recipes, null, 2)};
`;
writeFileSync(join(root, 'mcp/generated.ts'), out);
console.log(`gen-mcp-data: ${skills.length} skills, ${recipes.length} prompt recipes`);
